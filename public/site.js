// Shared by every page: the business details, header, footer and form helpers.

// Fill these in before launch. Anything left empty shows as a [bracketed]
// placeholder in the Terms of Use and Privacy Policy.
export const site = {
  company: "",       // legal name of the business that runs the site
  state: "",         // governing-law state, e.g. "Texas"
  contactEmail: "",  // public contact address
  updated: "",       // "Last updated" date on the legal pages
};

const placeholders = { company: "[Company name]", state: "[State]", contactEmail: "[contact email]", updated: "[date]" };

export const $ = (selector, root = document) => root.querySelector(selector);

function fill() {
  for (const el of document.querySelectorAll("[data-fill]")) {
    const key = el.dataset.fill;
    el.textContent = site[key] || el.dataset.or || placeholders[key];
    if (key === "contactEmail" && site.contactEmail && el.tagName === "A") el.href = `mailto:${site.contactEmail}`;
  }
}

function chrome() {
  const header = $("#header");
  if (header) {
    header.innerHTML = `
      <header class="top"><div class="wrap">
        <a class="brand" href="/">yourparttime<b>biz</b></a>
        <nav><a href="/#start">Get ideas</a><a href="/talk-to-us">Talk to us</a></nav>
      </div></header>`;
  }
  const footer = $("#footer");
  if (footer) {
    footer.innerHTML = `
      <footer class="foot"><div class="wrap">
        <p class="small">Business ideas on this site are general suggestions generated by AI. They are not legal, tax, or financial advice, and come with no guarantee of results.</p>
        <p class="small"><a href="/terms">Terms of Use</a> · <a href="/privacy">Privacy Policy</a> · <a href="/talk-to-us">Talk to us</a></p>
        <p class="small muted">© ${new Date().getFullYear()} ${site.company || "yourparttimebiz.com"}</p>
      </div></footer>`;
  }
}

/** Shows a message in a .msg box; kind is "bad" (default) or "ok". */
export function show(el, text, kind = "bad") {
  el.textContent = text;
  el.className = `msg on ${kind}`;
  el.scrollIntoView({ block: "nearest", behavior: "smooth" });
}

export async function post(path, body) {
  const res = await fetch(path, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(body) });
  if (!res.ok) {
    const data = await res.json().catch(() => ({}));
    throw new Error(data.error || "Something went wrong. Please try again.");
  }
  return res;
}

// Remembers what a visitor typed on this device, so a reload or a trip to the
// Terms page does not lose their answers. Never required for the site to work.
export const draft = {
  load() {
    try { return JSON.parse(localStorage.getItem("yptb_draft")) || {}; } catch { return {}; }
  },
  save(value) {
    try { localStorage.setItem("yptb_draft", JSON.stringify(value)); } catch {}
  },
};

